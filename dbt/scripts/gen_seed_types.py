"""Regenerate seeds/_seeds.yml: explicit column types for every fixture seed.

The fixtures mimic the Datastream raw tables, so each column gets the type Datastream gives it
in BigQuery (uuid/text -> string, timestamptz -> timestamp, date -> date, bigint -> int64,
numeric -> numeric, boolean -> bool), spelled for DuckDB. Explicit types keep CSV inference
from guessing (all-empty columns, digit strings like phone_last4).

Usage (from dbt/): uv run python scripts/gen_seed_types.py
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SEEDS = ROOT / "seeds" / "raw"
OUT = ROOT / "seeds" / "_seeds.yml"

BOOLEAN = {"own_brand", "consent_marketing", "phone_verified", "variance_flagged", "llm_used"}
DATE = {"expiry", "due_date", "harvest_month", "sowing_date", "expected_harvest", "business_date"}
BIGINT = {"score", "_ds_source_timestamp"}
DECIMAL = {"qty", "km", "area_acres"}


def column_type(name: str) -> str:
    if name in BOOLEAN:
        return "boolean"
    if name in DATE:
        return "date"
    if name.endswith("_at"):
        return "timestamp"
    if name in BIGINT or name.endswith("_paise"):
        return "bigint"
    if name in DECIMAL:
        return "decimal(12,3)"
    return "varchar"


def render() -> str:
    lines = [
        "# GENERATED by scripts/gen_seed_types.py -- do not edit by hand.",
        "version: 2",
        "",
        "seeds:",
    ]
    for path in sorted(SEEDS.glob("*.csv")):
        with path.open(newline="") as fh:
            header = next(csv.reader(fh))
        lines.append(f"  - name: {path.stem}")
        lines.append("    config:")
        lines.append("      column_types:")
        for col in header:
            lines.append(f"        {col}: {column_type(col)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("seeds/_seeds.yml is stale: run uv run python scripts/gen_seed_types.py")
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
