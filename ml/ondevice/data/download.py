"""Download the pinned bootstrap datasets listed in data/sources.json into data/raw/.

Usage: uv run python data/download.py [--only rice_india,chili_cold]

Files are fetched from the Hugging Face Hub at the pinned revision and checked against
the recorded size and sha256 (SPEC 3.3: public data is for bootstrapping only). Existing
files with the right size and hash are skipped, so the command is idempotent. Nothing
under data/raw/ is committed (see ml/ondevice/.gitignore).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import urllib.request
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent
RAW_DIR = DATA_DIR / "raw"
SOURCES = DATA_DIR / "sources.json"
HF = "https://huggingface.co/datasets/{repo}/resolve/{revision}/{path}"


def load_sources() -> list[dict]:
    return json.loads(SOURCES.read_text())["sources"]


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def local_path(source: dict, file: dict) -> Path:
    return RAW_DIR / source["id"] / file["path"]


def fetch(url: str, dest: Path, size: int) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    req = urllib.request.Request(url, headers={"User-Agent": "farmerapp-ondevice/1.0"})
    with urllib.request.urlopen(req, timeout=120) as resp, tmp.open("wb") as out:
        done = 0
        while chunk := resp.read(1 << 20):
            out.write(chunk)
            done += len(chunk)
            if size:
                print(f"\r  {dest.name}: {done / 1e6:7.1f} / {size / 1e6:.1f} MB", end="", flush=True)
    print()
    tmp.replace(dest)


def download(source: dict) -> None:
    if source["format"] == "synthetic":
        print(f"{source['id']}: generated by data/prepare.py, nothing to download")
        return
    for file in source["files"]:
        dest = local_path(source, file)
        if dest.exists() and dest.stat().st_size == file["size"]:
            print(f"{source['id']}: {file['path']} present")
        else:
            url = HF.format(repo=source["repo"], revision=source["revision"], path=file["path"])
            print(f"{source['id']}: downloading {url}")
            fetch(url, dest, file["size"])
        if dest.stat().st_size != file["size"]:
            sys.exit(f"{dest}: size {dest.stat().st_size} != pinned {file['size']}")
        if file.get("sha256"):
            digest = sha256_of(dest)
            if digest != file["sha256"]:
                sys.exit(f"{dest}: sha256 {digest} != pinned {file['sha256']}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--only", default="", help="comma-separated source ids")
    args = parser.parse_args()
    wanted = {s for s in args.only.split(",") if s}
    for source in load_sources():
        if not wanted or source["id"] in wanted:
            download(source)


if __name__ == "__main__":
    main()
