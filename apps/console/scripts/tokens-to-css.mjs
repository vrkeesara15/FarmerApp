#!/usr/bin/env node
/**
 * tokens-to-css: generates app/tokens.css from design/tokens.json (W3C Design Tokens).
 *
 * Output:
 *   :root                 -> light theme (default $value)
 *   [data-theme="dark"]   -> dark overrides ($extensions.theme.dark), falling back to light
 *
 * Semantic variable names: --color-primary, --color-primary-hover, --color-surface,
 * --text-body-size / -line / -weight, --space-4, --radius-card, --font-weight-semibold ...
 * Run via `npm run tokens` (also `prebuild`). Output is committed so the app builds without it.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS = resolve(here, "../../../design/tokens.json");
const OUT = resolve(here, "../app/tokens.css");
const THEMES = ["light", "dark"]; // sunlight is mobile-only

const tokens = JSON.parse(readFileSync(TOKENS, "utf8"));

const kebab = (s) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase();

/** Resolve {a.b.c} alias references against the token tree. */
function resolveAlias(value, theme, depth = 0) {
  if (typeof value !== "string" || !/^\{.+\}$/.test(value)) return value;
  if (depth > 10) throw new Error(`Alias loop at ${value}`);
  const path = value.slice(1, -1).split(".");
  let node = tokens;
  for (const p of path) {
    node = node?.[p];
    if (node === undefined) throw new Error(`Unresolved alias ${value}`);
  }
  return resolveAlias(themedValue(node, theme), theme, depth + 1);
}

function themedValue(token, theme) {
  const override = token.$extensions?.theme?.[theme];
  return override !== undefined ? override : token.$value;
}

/** Build a flat name->value map for the given theme. */
function flatten(node, path, theme, out) {
  if (node && typeof node === "object" && "$value" in node) {
    const name = path.join("-");
    const raw = themedValue(node, theme);
    const value = resolveAlias(raw, theme);
    switch (node.$type) {
      case "color":
        out.set(`--${name}`, value);
        break;
      case "dimension":
        out.set(`--${name}`, `${value}px`);
        break;
      case "fontWeight":
      case "number":
      case "string":
        out.set(`--${name}`, String(value));
        break;
      case "fontFamily":
        out.set(`--${name}-stack`, value.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", "));
        break;
      case "typography": {
        const v = value;
        const px = (x) => String(x).replace(/sp$/, "px");
        out.set(`--${name}-size`, px(v.fontSize));
        out.set(`--${name}-line`, px(v.lineHeight));
        out.set(`--${name}-weight`, String(v.fontWeight));
        break;
      }
      case "shadow":
        if (value === "none" || typeof value === "string") out.set(`--${name}`, String(value));
        else
          out.set(
            `--${name}`,
            `${value.offsetX}px ${value.offsetY}px ${value.blur}px ${value.spread}px ${value.color}`,
          );
        break;
      default:
        out.set(`--${name}`, String(value));
    }
    return;
  }
  if (node && typeof node === "object") {
    for (const [k, v] of Object.entries(node)) {
      if (k.startsWith("$")) continue;
      flatten(v, [...path, kebab(k)], theme, out);
    }
  }
}

/** Rename generated keys to the semantic names the Tailwind theme consumes. */
function semantic(name) {
  return name
    .replace(/^--color-(primary|secondary|text)-default$/, "--color-$1")
    .replace(/^--color-status-/, "--color-")
    .replace(/^--text-console-/, "--text-")
    .replace(/^--font-family-/, "--font-family-");
}

function block(selector, map, exclude = new Set()) {
  const lines = [...map.entries()]
    .map(([k, v]) => [semantic(k), v])
    .filter(([k]) => !exclude.has(k))
    .map(([k, v]) => `  ${k}: ${v};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

const light = new Map();
flatten(tokens, [], "light", light);
const dark = new Map();
flatten(tokens, [], "dark", dark);

// Dark block only carries values that differ from light.
const darkDiff = new Map([...dark].filter(([k, v]) => light.get(k) !== v));

const header = `/* GENERATED by scripts/tokens-to-css.mjs from design/tokens.json — do not edit by hand. */\n`;
const css =
  header +
  block(':root, [data-theme="light"]', light) +
  `\n${block('[data-theme="dark"]', darkDiff)}` +
  `\n/* Mobile-only text scale is emitted for reference; console uses --text-* (display/title/heading/body/small). */\n`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css);
console.log(
  `tokens-to-css: wrote ${OUT} (${light.size} light vars, ${darkDiff.size} dark overrides) for themes ${THEMES.join(", ")}`,
);
