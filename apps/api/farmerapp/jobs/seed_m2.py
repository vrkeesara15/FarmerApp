"""M2 part of the demo seed: duty sessions, location tracks, visits, photos, confirmations
and policy acceptances for the officers generated by ``farmerapp.jobs.seed`` (M2-KICKOFF).

Per officer and duty day (``SeedProfile.duty_days`` days ending on ``SEED_TODAY``):

* one ``duty_session`` 09:00 (+-10 min) .. ~18:00 IST starting and ending at the store,
  ``end_reason`` mostly ``manual`` (one day in seven ``auto_time`` at 20:00, VV-007), km from
  the generated path, ``stops`` from the visits, a ``policy_acceptance`` before the first
  duty (VV-010);
* ``visits_per_day`` visits to the officer's own farmers, ordered village by village into a
  plausible route: check-in mostly inside the farm geofence (within 40 m of the farm
  centroid), some outside (300-600 m; recorded, blocked in the app), some overrides (with a
  note, approved by the cluster head), a few at the village meeting point (purpose
  ``meeting``); 1-3 in-app photos each (EXIF near the check-in; ~10 % gallery / far away
  for VA-E08), a confirmation for ~60 % (SMS OTP / app push / QR); the FA-028 flags on a
  few officer-days (mock location, clock drift); score and status from
  ``farmerapp.visits.scoring`` so the demo agrees with the write path;
* ``location_point`` rows every 2 min (+-30 s) while moving between waypoints (at ~30 km/h
  with ~15 m jitter) and every 10 min while stationary at a visit (VV-001), with accuracy,
  speed, bearing, battery, provider, mock / root flags and clock drift (VV-002), received
  15-30 min after the sample (batch upload).

Ids are ``uuid5`` of the tenant and a natural key, so the seed stays idempotent.
"""

