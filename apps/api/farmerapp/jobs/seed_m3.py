"""M3 part of the demo seed: catalogue, label claims, stock, orders, payments, khata, credit
limits, webhook events and day closes for the tenants generated by ``farmerapp.jobs.seed``
(M3-KICKOFF).

Per tenant (``M3Profile`` scales it; ``M3_SMALL`` is the test fixture):

* the ``farmerapp.jobs.seed_catalog`` products with their SKUs (barcodes, MRP), a tenant
  default price per SKU (own brand 5 % under MRP, multi-brand at MRP) valid since 120 days,
  a few store overrides on the first store (one of them expired, for the resolver), the
  pest / disease master and the label-claim fixtures (approved 90 days ago; every 20th
  claim left as ``draft`` and every 50th ``retired`` so WC-005 has something to review);
* stock: per store ~65 % of the SKUs with 1-2 batches received in the last 120 days, a
  receipt movement each, a few damage write-offs, one transfer between the first two
  stores; the first three stocked SKUs of every store expire in 20 days and the next three
  in 50 (ST-004 fixtures). ``stock_batch.qty`` is the sum of the batch's movements;
* orders over the last ``history_days`` days across the channels (POS 45 %, officer 40 %,
  farmer app 15 %; ~30 % of POS sales are walk-ins) with 1-4 lines priced by the price
  resolver, GST from the product, ``label_claim_id`` on officer lines that carry an approved
  claim, statuses by age (older: delivered / handed over, a few cancelled; recent: the
  ST-005 queue), invoice numbers on fulfilled orders and the sale movements that fulfilled
  them;
* payments by mode (cash 40 %, UPI QR 30 %, credit 20 %, payment link 5 %, card 5 %):
  provider payments carry a Razorpay-style ``pay_`` / ``evt_`` id and a processed
  ``webhook_event``; cash is ``reconciled`` on past days and ``pending`` today; ``credit``
  writes the khata debit (due at the farmer's next expected harvest, else +90 days) and
  points to it; half the credit farmers repay part of it later (a khata credit + a cash /
  UPI payment against it);
* eight "opening balance" debits dated 100-130 days ago and overdue for more than 90 days
  (VA-F10 fixtures), a credit limit for every farmer with a debit (cluster head approval
  above 50,000), and a day close per store for the last three business days (cash expected
  from the day's cash payments; one store one day 250 short).

Ids are ``uuid5`` of the tenant and a natural key, so the seed stays idempotent.
"""

