def _weighted(rng: random.Random, weights: Sequence[tuple[Any, int]]) -> Any:
    return rng.choices([w[0] for w in weights], weights=[w[1] for w in weights], k=1)[0]


def _at(day: date, hour: int, minute: int = 0) -> datetime:
    return datetime.combine(day, time(hour, minute), tzinfo=IST).astimezone(UTC)


def _month_start(day: date) -> date:
    return day.replace(day=1)


class M3Generator:
    def __init__(
        self,
        tenant_id: uuid.UUID,
        slug: str,
        rng: random.Random,
        profile: M3Profile,
        *,
        today: date,
        users: Sequence[User],
        rows: Mapping[str, list[Any]],
        add: Callable[[Any], None],
    ) -> None:
        self.tid, self.slug, self.rng, self.profile = tenant_id, slug, rng, profile
        self.today, self.add = today, add
        self.users = list(users)
        self.stores: list[Store] = sorted(rows["store"], key=lambda s: s.code)
        self.crops: dict[str, Crop] = {c.code: c for c in rows["crop"]}
        self.villages: dict[uuid.UUID, Village] = {v.id: v for v in rows["village"]}
        self.farmers: list[Farmer] = list(rows["farmer"])
        self.farms: dict[uuid.UUID, list[Farm]] = {}
        for farm in rows["farm"]:
            self.farms.setdefault(farm.farmer_id, []).append(farm)
        self.plots: dict[uuid.UUID, list[CropPlot]] = {}
        for plot in rows["crop_plot"]:
            self.plots.setdefault(plot.farm_id, []).append(plot)
        self.skus: list[_Sku] = []
        self.prices: list[PriceList] = []
        self.batches: dict[uuid.UUID, list[_Batch]] = {}  # store id -> batches
        self.by_store_sku: dict[tuple[uuid.UUID, uuid.UUID], list[_Batch]] = {}
        self.cash_by_store_day: dict[tuple[uuid.UUID, date], int] = {}
        self.debited: dict[tuple[uuid.UUID, uuid.UUID], int] = {}  # (farmer, store) -> paise
        self.order_seq = 0
        self.invoice_seq: dict[str, int] = {}

    # ------------------------------------------------------------------ helpers
    def _sid(self, kind: str, key: str) -> uuid.UUID:
        return uuid.uuid5(self.tid, f"{kind}:{key}")

    def _role(self, role: UserRole) -> User:
        return next(u for u in self.users if u.role == role)

    def _store_manager(self, store: Store) -> User:
        for u in self.users:
            if u.role == UserRole.STORE_MANAGER and u.store_id == store.id:
                return u
        return self._role(UserRole.ACCOUNTANT)

    def _cluster_head(self, store: Store) -> User | None:
        for u in self.users:
            if u.role == UserRole.CLUSTER_HEAD and u.cluster_id == store.cluster_id:
                return u
        return None

    def _store_of(self, farmer: Farmer) -> Store | None:
        village = self.villages.get(farmer.village_id)
        if village is None or village.store_id is None:
            return None
        return next((s for s in self.stores if s.id == village.store_id), None)

    def _farmers_of(self, store: Store) -> list[Farmer]:
        return [f for f in self.farmers if self._store_of(f) is store]

    def _harvest(self, farmer: Farmer, after: date) -> date:
        """The farmer's next expected harvest after ``after`` (else +90 days)."""
        candidates = [
            p.expected_harvest
            for farm in self.farms.get(farmer.id, [])
            for p in self.plots.get(farm.id, [])
            if p.expected_harvest is not None and p.expected_harvest > after
        ]
        return min(candidates) if candidates else after + timedelta(days=90)

    # ------------------------------------------------------------------ catalogue
    def _catalogue(self) -> None:
        label = own_brand_label(self.slug)
        products = [
            p
            for p in PRODUCTS
            if self.profile.product_keys is None or p.key in self.profile.product_keys
        ]
        problems: dict[str, PestOrDisease] = {}
        needed = {c.problem for p in products for c in p.claims}
        for pspec in PROBLEMS:
            if self.profile.small and pspec.code not in needed:
                continue
            crop = self.crops.get(pspec.crop) if pspec.crop else None
            if pspec.crop and crop is None:
                continue
            master = PestOrDisease(
                id=self._sid("pest_or_disease", pspec.code),
                tenant_id=self.tid,
                code=pspec.code,
                name=pspec.name,
                names=dict(pspec.names),
                type=pspec.type,
                crop_id=crop.id if crop is not None else None,
                scientific_name=pspec.scientific_name,
                symptoms=pspec.symptoms,
            )
            problems[pspec.code] = master
            self.add(master)

        since = self.today - timedelta(days=120)
        approved_at = _at(self.today - timedelta(days=90), 11)
        claim_n = 0
        for spec in products:
            product = Product(
                id=self._sid("product", spec.key),
                tenant_id=self.tid,
                name=spec.name.replace(OWN, label),
                brand=spec.brand.replace(OWN, label),
                own_brand=spec.own_brand,
                category=spec.category,
                hsn=spec.hsn,
                gst_rate_bp=spec.gst_rate_bp,
                description=spec.description,
                active_ingredient=spec.active_ingredient,
                formulation=spec.formulation,
                names=dict(spec.names),
            )
            self.add(product)
            for i, pack in enumerate(spec.packs):
                if self.profile.sku_cap is not None and len(self.skus) >= self.profile.sku_cap:
                    break
                key = f"{spec.key}/{i}"
                sku_id = self._sid("sku", key)
                sku = Sku(
                    id=sku_id,
                    tenant_id=self.tid,
                    product_id=product.id,
                    pack_size_value=Decimal(pack.value),
                    pack_size_unit=pack.unit,
                    barcode=f"890{int(sku_id.hex[:10], 16) % 10**10:010d}",
                    mrp_paise=pack.mrp_paise,
                )
                self.add(sku)
                price = pack.mrp_paise * 95 // 100 if spec.own_brand else pack.mrp_paise
                default = PriceList(
                    id=self._sid("price_list", f"{key}/default"),
                    tenant_id=self.tid,
                    store_id=None,
                    sku_id=sku_id,
                    price_paise=price,
                    effective_from=since,
                )
                self.prices.append(default)
                self.add(default)
                entry = _Sku(spec, sku, key, [])
                self.skus.append(entry)
                for claim in spec.claims:
                    if self.profile.claim_cap is not None and claim_n >= self.profile.claim_cap:
                        break
                    claim_crop = self.crops.get(claim.crop)
                    target = problems.get(claim.problem)
                    if claim_crop is None or target is None:
                        continue
                    claim_n += 1
                    status = ClaimStatus.APPROVED
                    if not self.profile.small:
                        if claim_n % 50 == 0:
                            status = ClaimStatus.RETIRED
                        elif claim_n % 20 == 0:
                            status = ClaimStatus.DRAFT
                    safety = SAFETY_TEXT
                    if spec.category == ProductCategory.FERTILISER:
                        safety = NUTRIENT_SAFETY_TEXT
                    elif spec.category == ProductCategory.HERBICIDE:
                        safety = HERBICIDE_SAFETY_TEXT
                    row = LabelClaim(
                        id=self._sid("label_claim", f"{key}/{claim.crop}/{claim.problem}"),
                        tenant_id=self.tid,
                        sku_id=sku_id,
                        crop_id=claim_crop.id,
                        pest_or_disease_id=target.id,
                        dose_per_acre=claim.dose_per_acre,
                        dose_value=Decimal(claim.dose_value),
                        dose_unit=claim.dose_unit,
                        dose_per_tank_15l=claim.dose_per_tank_15l,
                        phi_days=claim.phi_days,
                        ppe_text=PPE_TEXT if target.type != ProblemType.NUTRIENT else None,
                        safety_text=safety,
                        source_ref=SEED_SOURCE_REF,
                        efficacy_tier=claim.efficacy_tier,
                        status=status,
                        approved_by=None,
                        approved_at=approved_at if status != ClaimStatus.DRAFT else None,
                    )
                    entry.claims.append(row)
                    self.add(row)
        # Store overrides on the first store: five SKUs 8 % under the default since 30 days,
        # plus an expired override (ended 40 days ago) the resolver must ignore.
        if self.stores and not self.profile.small:
            store = self.stores[0]
            for entry in self.skus[:5]:
                base = next(p for p in self.prices if p.sku_id == entry.sku.id)
                for n, (frm, to, factor) in enumerate(
                    (
                        (self.today - timedelta(days=30), None, 92),
                        (self.today - timedelta(days=100), self.today - timedelta(days=40), 80),
                    )
                ):
                    override = PriceList(
                        id=self._sid("price_list", f"{entry.key}/{store.code}/{n}"),
                        tenant_id=self.tid,
                        store_id=store.id,
                        sku_id=entry.sku.id,
                        price_paise=base.price_paise * factor // 100,
                        effective_from=frm,
                        effective_to=to,
                    )
                    self.prices.append(override)
                    self.add(override)

    def _price(self, sku: Sku, store: Store, at: date) -> int:
        rows = [p for p in self.prices if p.sku_id == sku.id]
        return resolved_price(resolve(rows, store.id, at), sku.mrp_paise)

    # ------------------------------------------------------------------ stock
    def _stock(self) -> None:
        rng = self.rng
        for store in self.stores:
            stocked = [
                e
                for e in self.skus
                if self.profile.small or rng.random() < self.profile.stocked_share
            ]
            if self.profile.small:
                # One batch per store, of a SKU with an approved claim (so the fixture
                # officer order can carry a label_claim_id, DX-007).
                with_claims = [e for e in stocked if e.claims]
                stocked = (with_claims or stocked)[:1]
            self.batches[store.id] = []
            for i, entry in enumerate(stocked):
                n_batches = rng.randint(*self.profile.batches_per_sku)
                for b in range(n_batches):
                    received_day = self.today - timedelta(days=rng.randint(5, 120))
                    if i < 3 and b == 0:
                        expiry = self.today + timedelta(days=20)  # ST-004: 30-day alert
                    elif i < 6 and b == 0:
                        expiry = self.today + timedelta(days=50)  # ST-004: 60-day alert
                    elif entry.product.category == ProductCategory.TOOL:
                        expiry = None
                    else:
                        expiry = received_day + timedelta(days=rng.randint(365, 900))
                    qty = Decimal(rng.randint(10, 200))
                    key = f"{store.code}/{entry.key}/{b}"
                    received_at = _at(received_day, rng.randint(10, 16), rng.randint(0, 59))
                    batch = StockBatch(
                        id=self._sid("stock_batch", key),
                        tenant_id=self.tid,
                        store_id=store.id,
                        sku_id=entry.sku.id,
                        batch_no=f"B{received_day:%y%m}-{b + 1:03d}",
                        expiry=expiry,
                        qty=qty,
                        cost_paise=entry.sku.mrp_paise * 70 // 100,
                        received_at=received_at,
                        created_at=received_at,
                        updated_at=received_at,
                    )
                    self.add(batch)
                    self._move(
                        batch,
                        MovementKind.RECEIPT,
                        qty,
                        received_at,
                        f"{key}/receipt",
                        ref_type="grn",
                        note=f"GRN {batch.batch_no}",
                    )
                    tracked = _Batch(batch, key, qty)
                    self.batches[store.id].append(tracked)
                    self.by_store_sku.setdefault((store.id, entry.sku.id), []).append(tracked)
                    if not self.profile.small and rng.random() < 0.08 and qty > 5:
                        damaged = Decimal(rng.randint(1, 3))
                        self._move(
                            batch,
                            MovementKind.DAMAGE,
                            -damaged,
                            received_at + timedelta(days=2),
                            f"{key}/damage",
                            note="Leaking containers written off",
                        )
                        tracked.remaining -= damaged
                        batch.qty = tracked.remaining
        # One transfer between the first two stores (a SKU both stock).
        if len(self.stores) >= 2 and not self.profile.small:
            src_store, dst_store = self.stores[0], self.stores[1]
            shared = [
                e
                for e in self.skus
                if (src_store.id, e.sku.id) in self.by_store_sku
                and (dst_store.id, e.sku.id) in self.by_store_sku
            ]
            if shared:
                entry = shared[0]
                src = self.by_store_sku[(src_store.id, entry.sku.id)][0]
                dst = self.by_store_sku[(dst_store.id, entry.sku.id)][0]
                moved = min(Decimal(5), src.remaining)
                when = _at(self.today - timedelta(days=3), 12)
                ref = self._sid("transfer", f"{src_store.code}->{dst_store.code}/{entry.key}")
                self._move(
                    src.batch,
                    MovementKind.TRANSFER_OUT,
                    -moved,
                    when,
                    f"{src.key}/transfer_out",
                    ref_type="transfer",
                    ref_id=ref,
                )
                self._move(
                    dst.batch,
                    MovementKind.TRANSFER_IN,
                    moved,
                    when,
                    f"{dst.key}/transfer_in",
                    ref_type="transfer",
                    ref_id=ref,
                )
                src.remaining -= moved
                dst.remaining += moved
                src.batch.qty, dst.batch.qty = src.remaining, dst.remaining

    def _move(
        self,
        batch: StockBatch,
        kind: MovementKind,
        qty: Decimal,
        at: datetime,
        key: str,
        *,
        ref_type: str | None = None,
        ref_id: uuid.UUID | None = None,
        note: str | None = None,
    ) -> None:
        self.add(
            StockMovement(
                id=self._sid("stock_movement", key),
                tenant_id=self.tid,
                created_at=at,
                store_id=batch.store_id,
                sku_id=batch.sku_id,
                batch_id=batch.id,
                kind=kind,
                qty=qty,
                ref_type=ref_type,
                ref_id=ref_id,
                note=note,
            )
        )

    # ------------------------------------------------------------------ orders
    def _orders(self) -> None:
        rng = self.rng
        orders = self.profile.orders or FULL_ORDERS
        total = orders.get(self.slug, 0)
        stores = [s for s in self.stores if self.batches.get(s.id)]
        if not stores or not self.skus:
            return
        if self.profile.small:
            self._small_orders()
            return
        weights = [max(len(self._farmers_of(s)), 1) for s in stores]
        for _ in range(total):
            store = rng.choices(stores, weights=weights, k=1)[0]
            age = int(rng.triangular(0, self.profile.history_days, 3))
            day = self.today - timedelta(days=age)
            channel = _weighted(rng, CHANNEL_WEIGHTS)
            farmers = self._farmers_of(store)
            farmer = (
                None
                if (channel == OrderChannel.POS and rng.random() < 0.3)
                else (rng.choice(farmers) if farmers else None)
            )
            if age > 7:
                status = _weighted(
                    rng,
                    (
                        (OrderStatus.DELIVERED, 46),
                        (OrderStatus.HANDED_OVER, 46),
                        (OrderStatus.CANCELLED, 8),
                    ),
                )
            elif age > 1:
                status = _weighted(
                    rng,
                    (
                        (OrderStatus.DELIVERED, 35),
                        (OrderStatus.HANDED_OVER, 35),
                        (OrderStatus.READY, 10),
                        (OrderStatus.PACKED, 10),
                        (OrderStatus.CANCELLED, 5),
                        (OrderStatus.RESERVED, 5),
                    ),
                )
            else:
                status = _weighted(
                    rng,
                    (
                        (OrderStatus.PLACED, 30),
                        (OrderStatus.RESERVED, 25),
                        (OrderStatus.PACKED, 20),
                        (OrderStatus.READY, 15),
                        (OrderStatus.HANDED_OVER, 10),
                    ),
                )
            if channel == OrderChannel.POS and status in (
                OrderStatus.PLACED,
                OrderStatus.RESERVED,
                OrderStatus.PACKED,
                OrderStatus.READY,
                OrderStatus.DELIVERED,
            ):
                status = OrderStatus.HANDED_OVER  # a counter sale is handed over at once
            if status == OrderStatus.DELIVERED:
                fulfilment = Fulfilment.DELIVERY
            elif status == OrderStatus.HANDED_OVER or channel == OrderChannel.POS:
                fulfilment = Fulfilment.PICKUP
            else:
                fulfilment = rng.choice((Fulfilment.PICKUP, Fulfilment.DELIVERY))
            self._order(store, farmer, channel, status, fulfilment, day)

    def _small_orders(self) -> None:
        """Three fixed orders for the fixtures at the demo farmer's store: a delivered credit
        order placed by the farmer's officer (repaid in part later), a placed farmer-app order
        by the demo farmer login, a walk-in cash sale. Keys / invoices are ``s``-prefixed so a
        FULL seed on top never collides with them."""
        farmer = next((f for f in self.farmers if f.user_id is not None), self.farmers[0])
        store = self._store_of(farmer) or self.stores[0]
        officer = next(
            (u for u in self.users if u.id == farmer.registered_by),
            self._role(UserRole.FIELD_OFFICER),
        )
        self._order(
            store,
            farmer,
            OrderChannel.OFFICER,
            OrderStatus.DELIVERED,
            Fulfilment.DELIVERY,
            self.today - timedelta(days=10),
            placed_by=officer,
            mode=PaymentMode.CREDIT,
        )
        self._order(
            store,
            farmer,
            OrderChannel.FARMER_APP,
            OrderStatus.PLACED,
            Fulfilment.PICKUP,
            self.today,
            placed_by=self._farmer_user(farmer),
        )
        self._order(
            store,
            None,
            OrderChannel.POS,
            OrderStatus.HANDED_OVER,
            Fulfilment.PICKUP,
            self.today - timedelta(days=1),
            mode=PaymentMode.CASH,
        )

    def _farmer_user(self, farmer: Farmer) -> User | None:
        return next((u for u in self.users if u.id == farmer.user_id), None)

    def _placed_by(self, store: Store, farmer: Farmer | None, channel: OrderChannel) -> User | None:
        if channel == OrderChannel.POS:
            return self._store_manager(store)
        if channel == OrderChannel.FARMER_APP:
            return self._farmer_user(farmer) if farmer is not None else None
        if farmer is not None and farmer.registered_by is not None:
            return next((u for u in self.users if u.id == farmer.registered_by), None)
        return None

    def _order(
        self,
        store: Store,
        farmer: Farmer | None,
        channel: OrderChannel,
        status: OrderStatus,
        fulfilment: Fulfilment,
        day: date,
        *,
        placed_by: User | None = None,
        mode: PaymentMode | None = None,
    ) -> None:
        rng = self.rng
        self.order_seq += 1
        prefix = "s" if self.profile.small else ""
        key = f"{self.slug}/{prefix}{self.order_seq:04d}"
        placed_at = _at(day, rng.randint(9, 17), rng.randint(0, 59))
        placed_by = placed_by or self._placed_by(store, farmer, channel)
        fulfilled = status in (OrderStatus.HANDED_OVER, OrderStatus.DELIVERED)
        fulfilled_at = placed_at + timedelta(
            minutes=rng.randint(10, 60) if channel == OrderChannel.POS else rng.randint(60, 1440)
        )
        if fulfilled_at.astimezone(IST).date() > self.today:
            fulfilled_at = _at(self.today, 17, 30)
        stocked = [e for e in self.skus if (store.id, e.sku.id) in self.by_store_sku]
        n_lines = 1 if self.profile.small else rng.randint(1, min(4, len(stocked)))
        chosen = rng.sample(stocked, k=min(n_lines, len(stocked)))
        subtotal = tax = 0
        lines: list[OrderLine] = []
        for i, entry in enumerate(chosen):
            qty = Decimal(rng.randint(1, 5))
            unit = self._price(entry.sku, store, day)
            total = line_total_paise(qty, unit)
            approved = [c for c in entry.claims if c.status == ClaimStatus.APPROVED]
            claim = rng.choice(approved) if approved and channel == OrderChannel.OFFICER else None
            batch = None
            if fulfilled or status in (OrderStatus.RESERVED, OrderStatus.PACKED, OrderStatus.READY):
                candidates = [
                    b for b in self.by_store_sku[(store.id, entry.sku.id)] if b.remaining >= qty
                ]
                batch = candidates[0] if candidates else None
            line = OrderLine(
                id=self._sid("order_line", f"{key}/{i}"),
                tenant_id=self.tid,
                order_id=self._sid("order", key),
                sku_id=entry.sku.id,
                batch_id=batch.batch.id if batch is not None else None,
                qty=qty,
                unit_price_paise=unit,
                gst_rate_bp=entry.product.gst_rate_bp,
                line_total_paise=total,
                label_claim_id=claim.id if claim is not None else None,
                created_at=placed_at,
                updated_at=placed_at,
            )
            lines.append(line)
            subtotal += total
            tax += tax_paise(total, entry.product.gst_rate_bp)
            if fulfilled and batch is not None:
                self._move(
                    batch.batch,
                    MovementKind.SALE,
                    -qty,
                    fulfilled_at,
                    f"{key}/{i}/sale",
                    ref_type="order",
                    ref_id=line.order_id,
                )
                batch.remaining -= qty
                batch.batch.qty = batch.remaining
        discount = subtotal * 5 // 100 if (not self.profile.small and rng.random() < 0.1) else 0
        invoice = None
        if fulfilled:
            n = self.invoice_seq.get(store.code, 0) + 1
            self.invoice_seq[store.code] = n
            invoice = f"{store.code}/26-27/{prefix.upper()}{n:05d}"
        order = Order(
            id=self._sid("order", key),
            tenant_id=self.tid,
            farmer_id=farmer.id if farmer is not None else None,
            store_id=store.id,
            channel=channel,
            status=status,
            fulfilment=fulfilment,
            subtotal_paise=subtotal,
            discount_paise=discount,
            tax_paise=tax,
            total_paise=subtotal - discount + tax,
            placed_by=placed_by.id if placed_by is not None else None,
            placed_at=placed_at,
            notes=rng.choice(ORDER_NOTES),
            invoice_no=invoice,
            client_order_id=self._sid("client_order", key) if channel != OrderChannel.POS else None,
            created_at=placed_at,
            updated_at=fulfilled_at if fulfilled else placed_at,
        )
        self.add(order)
        for line in lines:
            self.add(line)
        if fulfilled and order.total_paise > 0:
            if mode is None:
                mode = _weighted(rng, MODE_WEIGHTS)
                if farmer is None and mode == PaymentMode.CREDIT:
                    mode = PaymentMode.CASH  # walk-ins never buy on credit
            self._payment(key, order, store, farmer, placed_by, mode, fulfilled_at)

    # ------------------------------------------------------------------ payments / khata
    def _payment(
        self,
        key: str,
        order: Order,
        store: Store,
        farmer: Farmer | None,
        collected_by: User | None,
        mode: PaymentMode,
        at: datetime,
    ) -> None:
        rng = self.rng
        day = at.astimezone(IST).date()
        provider = (
            PaymentProvider.RAZORPAY
            if mode in (PaymentMode.UPI_QR, PaymentMode.PAYMENT_LINK)
            else PaymentProvider.NONE
        )
        payment = Payment(
            id=self._sid("payment", f"{key}/pay"),
            tenant_id=self.tid,
            order_id=order.id,
            farmer_id=farmer.id if farmer is not None else None,
            store_id=store.id,
            mode=mode,
            amount_paise=order.total_paise,
            provider=provider,
            collected_by=collected_by.id if collected_by is not None else None,
            created_at=at,
            updated_at=at,
        )
        if provider == PaymentProvider.RAZORPAY:
            ref = self._sid("provider_ref", key).hex[:14]
            payment.provider_ref = f"pay_{ref}"
            payment.provider_event_id = f"evt_{ref}"
            payment.status = PaymentStatus.PAID
            payment.paid_at = at + timedelta(seconds=rng.randint(20, 240))
            self.add(
                WebhookEvent(
                    id=self._sid("webhook_event", f"{key}/webhook"),
                    tenant_id=self.tid,
                    provider=provider,
                    event_id=payment.provider_event_id,
                    event_type="payment.captured",
                    signature_ok=True,
                    payload={
                        "event": "payment.captured",
                        "payload": {
                            "payment": {
                                "entity": {
                                    "id": payment.provider_ref,
                                    "amount": order.total_paise,
                                    "currency": "INR",
                                    "status": "captured",
                                    "notes": {"order_id": str(order.id)},
                                }
                            }
                        },
                    },
                    received_at=payment.paid_at,
                    processed_at=payment.paid_at + timedelta(seconds=1),
                    status=WebhookStatus.PROCESSED,
                    created_at=payment.paid_at,
                    updated_at=payment.paid_at,
                )
            )
        elif mode == PaymentMode.CASH:
            payment.status = PaymentStatus.RECONCILED if day < self.today else PaymentStatus.PENDING
            payment.paid_at = at
            payment.receipt_uri = f"gs://{RECEIPTS_BUCKET}/{self.tid}/receipt/{payment.id.hex}.jpg"
            self.cash_by_store_day[(store.id, day)] = (
                self.cash_by_store_day.get((store.id, day), 0) + order.total_paise
            )
        elif mode == PaymentMode.CARD_TERMINAL:
            payment.status = PaymentStatus.RECONCILED
            payment.paid_at = at
            payment.reference_note = f"TID 4471 RRN {int(payment.id.hex[:8], 16) % 10**12:012d}"
        else:  # credit: the sale goes on the khata (FA-021, ST-007)
            if farmer is None:
                raise ValueError("a credit sale needs a farmer")
            due = self._harvest(farmer, day)
            debit = KhataEntry(
                id=self._sid("khata_entry", f"{key}/debit"),
                tenant_id=self.tid,
                created_at=at,
                farmer_id=farmer.id,
                store_id=store.id,
                type=EntryType.DEBIT,
                amount_paise=order.total_paise,
                due_date=due,
                ref_type=EntryRef.ORDER,
                ref_id=order.id,
                note=f"Credit sale {order.invoice_no}",
                harvest_month=_month_start(due),
                created_by=collected_by.id if collected_by is not None else None,
            )
            self.add(debit)
            self.debited[(farmer.id, store.id)] = (
                self.debited.get((farmer.id, store.id), 0) + order.total_paise
            )
            payment.khata_entry_id = debit.id
            payment.status = PaymentStatus.RECONCILED
            payment.paid_at = at
            repay = self.profile.small or rng.random() < 0.5
            repay_day = day + timedelta(days=5 if self.profile.small else rng.randint(5, 40))
            if repay and repay_day < self.today:
                self._repayment(key, farmer, store, collected_by, debit, repay_day)
        self.add(payment)

    def _repayment(
        self,
        key: str,
        farmer: Farmer,
        store: Store,
        collected_by: User | None,
        debit: KhataEntry,
        day: date,
    ) -> None:
        rng = self.rng
        amount = debit.amount_paise * rng.randint(30, 100) // 100 or debit.amount_paise
        at = _at(day, rng.randint(9, 17), rng.randint(0, 59))
        credit = KhataEntry(
            id=self._sid("khata_entry", f"{key}/credit"),
            tenant_id=self.tid,
            created_at=at,
            farmer_id=farmer.id,
            store_id=store.id,
            type=EntryType.CREDIT,
            amount_paise=amount,
            ref_type=EntryRef.PAYMENT,
            ref_id=self._sid("payment", f"{key}/repay"),
            note="Khata repayment",
            created_by=collected_by.id if collected_by is not None else None,
        )
        self.add(credit)
        mode = PaymentMode.CASH if self.profile.small or rng.random() < 0.6 else PaymentMode.UPI_QR
        provider = PaymentProvider.RAZORPAY if mode == PaymentMode.UPI_QR else PaymentProvider.NONE
        repayment = Payment(
            id=credit.ref_id,
            tenant_id=self.tid,
            khata_entry_id=credit.id,
            farmer_id=farmer.id,
            store_id=store.id,
            mode=mode,
            amount_paise=amount,
            provider=provider,
            status=PaymentStatus.RECONCILED if mode == PaymentMode.CASH else PaymentStatus.PAID,
            paid_at=at,
            collected_by=collected_by.id if collected_by is not None else None,
            created_at=at,
            updated_at=at,
        )
        if provider == PaymentProvider.RAZORPAY:
            ref = self._sid("provider_ref", f"{key}/repay").hex[:14]
            repayment.provider_ref, repayment.provider_event_id = f"pay_{ref}", f"evt_{ref}"
        else:
            repayment.receipt_uri = (
                f"gs://{RECEIPTS_BUCKET}/{self.tid}/receipt/{repayment.id.hex}.jpg"
            )
            self.cash_by_store_day[(store.id, day)] = (
                self.cash_by_store_day.get((store.id, day), 0) + amount
            )
        self.add(repayment)

    def _opening_balances(self) -> None:
        """Migrated khata debits overdue for more than 90 days (VA-F10 fixtures)."""
        rng = self.rng
        candidates = [f for f in self.farmers if self._store_of(f) is not None]
        for farmer in candidates[: self.profile.opening_balances]:
            store = self._store_of(farmer)
            if store is None:
                continue
            day = self.today - timedelta(days=rng.randint(100, 130))
            due = self.today - timedelta(days=rng.randint(92, 100))
            amount = rng.randint(40, 300) * 10000  # 4,000 - 30,000 rupees
            at = _at(day, 10)
            self.add(
                KhataEntry(
                    id=self._sid("khata_entry", f"opening/{farmer.phone}"),
                    tenant_id=self.tid,
                    created_at=at,
                    farmer_id=farmer.id,
                    store_id=store.id,
                    type=EntryType.DEBIT,
                    amount_paise=amount,
                    due_date=due,
                    ref_type=EntryRef.ADJUSTMENT,
                    note="Opening balance (migrated khata)",
                    harvest_month=_month_start(due),
                    created_by=self._store_manager(store).id,
                )
            )
            self.debited[(farmer.id, store.id)] = (
                self.debited.get((farmer.id, store.id), 0) + amount
            )

    def _credit_limits(self) -> None:
        rng = self.rng
        by_id = {f.id: f for f in self.farmers}
        for (farmer_id, store_id), owed in sorted(self.debited.items(), key=lambda kv: str(kv[0])):
            store = next(s for s in self.stores if s.id == store_id)
            farmer = by_id[farmer_id]
            limit = max(rng.randint(4, 20) * 500000, (owed // 500000 + 1) * 500000)
            head = self._cluster_head(store)
            self.add(
                CreditLimit(
                    id=self._sid("credit_limit", f"{farmer.phone}/{store.code}"),
                    tenant_id=self.tid,
                    farmer_id=farmer_id,
                    store_id=store_id,
                    limit_paise=limit,
                    set_by=self._store_manager(store).id,
                    approved_by=head.id if head is not None and limit > 5_000_000 else None,
                )
            )

    def _day_closes(self) -> None:
        days = [self.today - timedelta(days=n) for n in range(1, self.profile.day_closes + 1)]
        # ST-006 fixture: the store-day with the most cash was counted 250 short.
        cash_days = [
            (self.cash_by_store_day.get((s.id, d), 0), s.code, d) for s in self.stores for d in days
        ]
        short = max(cash_days) if cash_days and not self.profile.small else None
        for store in self.stores:
            for day in days:
                expected = self.cash_by_store_day.get((store.id, day), 0)
                variance = (
                    -25000
                    if short is not None and (store.code, day) == short[1:] and expected >= 25000
                    else 0
                )
                closed_at = _at(day, 19, 30)
                self.add(
                    DayClose(
                        id=self._sid("day_close", f"{store.code}/{day.isoformat()}"),
                        tenant_id=self.tid,
                        store_id=store.id,
                        business_date=day,
                        cash_expected_paise=expected,
                        cash_counted_paise=expected + variance,
                        variance_paise=variance,
                        deposit_slip_uri=(
                            f"gs://{RECEIPTS_BUCKET}/{self.tid}/deposit/{store.code}-{day:%Y%m%d}.jpg"
                            if expected > 0
                            else None
                        ),
                        closed_by=self._store_manager(store).id,
                        closed_at=closed_at,
                        notes="Short by 250; counted twice" if variance else None,
                        created_at=closed_at,
                        updated_at=closed_at,
                    )
                )

    # ------------------------------------------------------------------ entry point
    def generate(self) -> None:
        self._catalogue()
        self._stock()
        self._orders()
        self._opening_balances()
        self._credit_limits()
        self._day_closes()


