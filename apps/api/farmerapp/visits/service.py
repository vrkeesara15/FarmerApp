async def check_out(
    session: AsyncSession, visit: Visit, body: VisitCheckOut, *, now: datetime | None = None
) -> Visit:
    """FA-017: close the visit and score it (VV-004 / VV-005); short visits are flagged."""
    if body.checkout_at < visit.checkin_at:
        raise CheckoutBeforeCheckinError("checkout_at must not precede checkin_at.")
    if visit.checkout_at is not None:
        if visit.checkout_at == body.checkout_at:
            return visit  # replay
        raise VisitAlreadyCheckedOutError("This visit is already checked out.")
    visit.checkout_at = body.checkout_at
    if body.checkout_point is not None:
        visit.checkout_point = point_wkt(body.checkout_point.lon, body.checkout_point.lat)
    await session.flush()
    await session.refresh(visit)  # the generated duration_s and the point properties
    await rescore(session, visit)
    log.info(
        "visit_checked_out",
        tenant_id=str(visit.tenant_id),
        visit_id=str(visit.id),
        duration_s=_duration_s(visit),
        score=visit.score,
        status=visit.status,
        flags=list(visit.flags or []),
    )
    await bus.dispatch(  # M4: VA-E08 re-checks the photos against the final visit window
        session, VisitCheckedOut(tenant_id=visit.tenant_id, visit_id=visit.id, at=now or _now())
    )
    return visit


