"""The visit write path (FA-014 .. FA-017, FA-028, VV-003 .. VV-005) — one implementation
behind the REST endpoints and ``POST /v1/sync``.

Flow (SPEC section 4 sequence diagram):

1. ``check_in`` — VV-003 geofence by PostGIS (``geofence.py``): ``inside`` / ``meeting_point``
   are accepted; ``outside`` is **rejected** with ``outside_geofence`` (distance + nearest
   target) unless the officer sends an ``override_note``, in which case the visit is created
   with ``geofence_result = override`` and an ``override_request`` the cluster head decides
   (``decide_override``). FA-028 integrity flags are recorded on the visit (``issues``), logged
   as ``integrity_signal`` and published as ``IntegrityEvent`` — never blocking.
2. ``capture`` — FA-015 notes / crop stage / purpose, last writer wins. ``add_photo`` —
   in-app photos only (``gallery_not_allowed``), server time, perceptual hash from the blob,
   EXIF / GPS mismatch against the check-in recorded as ``photo_flags`` (VA-E08), not rejected.
3. ``request_confirmation`` / ``confirm_with_otp`` / ``farmer_confirm`` — FA-016: the visit
   is confirmed only when one channel succeeds. ``sms_otp`` rides on the FA-001 OTP machinery
   (purpose ``farmer_confirm``, same limits and lockout) and completes on the officer's phone;
   ``app_push`` and ``qr`` hand the farmer's app a signed token (HS256 JWT ``typ =
   visit_confirm`` bound to tenant, visit and confirmation row) that it posts back, online,
   to the farmer-side endpoint — so a QR scanned offline is still validated later by the
   server. OTP confirmation needs connectivity by nature: the officer app can only queue the
   typed code (sync ``visit_confirmation.create``) and the server verifies it when the batch
   arrives (the code must still be within its 5-minute validity).
4. ``check_out`` — FA-017: duration is generated by the database; under the tenant minimum the
   visit is flagged ``under_minimum``, never rejected. ``rescore`` runs VV-004 / VV-005 and is
   called again whenever a later photo, confirmation or override decision arrives (idempotent:
   nothing is written when nothing changed).

Scope: an officer writes only their own visits (``own_visit``: 404 otherwise, like every
other out-of-scope row); a farmer confirms only visits made to their own record
(``visit_filters``); overrides are decided by the cluster head of the officer's cluster (or
an owner / director / tenant admin above them).
"""

