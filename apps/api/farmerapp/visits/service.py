def _now() -> datetime:
    return datetime.now(UTC)


def _device_of(actor: User) -> str | None:
    who = audit.current_actor()
    return (who.device_id if who is not None else None) or actor.device_id


def _sha(data: bytes | str) -> str:
    raw = data.encode() if isinstance(data, str) else data
    return hashlib.sha256(raw).hexdigest()


# --------------------------------------------------------------------------- lookups
async def visible_visit(session: AsyncSession, actor: User, visit_id: uuid.UUID) -> Visit:
    """One visit of the actor's tenant within the actor's 2.6 scope, else 404."""
    stmt = select(Visit).where(
        Visit.id == visit_id, Visit.deleted_at.is_(None), *visit_filters(actor)
    )
    visit = (await session.execute(stmt)).scalar_one_or_none()
    if visit is None:
        raise NotFoundError("Visit not found.")
    return visit


async def own_visit(session: AsyncSession, actor: User, visit_id: uuid.UUID) -> Visit:
    """The actor's own visit (writes are the visiting officer's; anything else is 404)."""
    visit = await visible_visit(session, actor, visit_id)
    if visit.officer_id != actor.id:
        raise NotFoundError("Visit not found.")
    return visit


async def settings_of(session: AsyncSession, tenant_id: uuid.UUID) -> TenantSettings:
    tenant = await session.get(Tenant, tenant_id)
    return tenant_settings(tenant.settings if tenant is not None else None)


async def _farmer(session: AsyncSession, tenant_id: uuid.UUID, farmer_id: uuid.UUID) -> Farmer:
    farmer = await session.get(Farmer, farmer_id)
    if farmer is None or farmer.tenant_id != tenant_id or farmer.deleted_at is not None:
        raise NotFoundError("Farmer not found.")
    return farmer


async def photos_of(session: AsyncSession, visit: Visit) -> list[VisitPhoto]:
    rows = await session.execute(
        select(VisitPhoto)
        .where(VisitPhoto.visit_id == visit.id, VisitPhoto.deleted_at.is_(None))
        .order_by(VisitPhoto.created_at, VisitPhoto.id)
    )
    return list(rows.scalars().all())


async def confirmations_of(session: AsyncSession, visit: Visit) -> list[VisitConfirmation]:
    rows = await session.execute(
        select(VisitConfirmation)
        .where(VisitConfirmation.visit_id == visit.id, VisitConfirmation.deleted_at.is_(None))
        .order_by(VisitConfirmation.created_at, VisitConfirmation.id)
    )
    return list(rows.scalars().all())


async def override_request_of(session: AsyncSession, visit: Visit) -> OverrideRequest | None:
    """The latest override request of the visit (pending or decided)."""
    return (
        await session.execute(
            select(OverrideRequest)
            .where(OverrideRequest.visit_id == visit.id, OverrideRequest.deleted_at.is_(None))
            .order_by(OverrideRequest.requested_at.desc(), OverrideRequest.id.desc())
            .limit(1)
        )
    ).scalar_one_or_none()


# --------------------------------------------------------------------------- scoring
def _duration_s(visit: Visit) -> int | None:
    if visit.checkout_at is None:
        return None
    return int((visit.checkout_at - visit.checkin_at).total_seconds())


async def rescore(session: AsyncSession, visit: Visit) -> Visit:
    """VV-004 / VV-005: recompute the components, score, status and duration flags.

    Idempotent: only differing values are assigned, so a rescore that changes nothing does
    not bump the row version or feed the sync change log.
    """
    await session.flush()
    await session.refresh(visit)  # pending writes expire the point column properties
    settings = await settings_of(session, visit.tenant_id)
    photos = await photos_of(session, visit)
    result = score_visit_row(visit, photos, min_duration_s=settings.min_visit_duration_s)
    if visit.score_components != result.components:
        visit.score_components = dict(result.components)
    flags = [f for f in (visit.flags or []) if f != FLAG_UNDER_MINIMUM]
    duration = _duration_s(visit)
    if duration is None:
        score: int | None = None
        status = VisitStatus.OPEN.value
    else:
        score = result.score
        status = result.status.value
        if duration < settings.min_visit_duration_s:
            flags.append(FLAG_UNDER_MINIMUM)
    if visit.score != score:
        visit.score = score
    if visit.status != status:
        visit.status = status
    if list(visit.flags or []) != flags:
        visit.flags = flags
    await session.flush()
    await session.refresh(visit)  # expired column properties (points) reload in async context
    return visit


# --------------------------------------------------------------------------- FA-028
def integrity_issues_of(body_integrity: dict[str, Any]) -> list[str]:
    issues: list[str] = []
    if body_integrity.get("is_mock"):
        issues.append(ISSUE_MOCK_LOCATION)
    if body_integrity.get("is_rooted"):
        issues.append(ISSUE_ROOTED_DEVICE)
    if abs(int(body_integrity.get("clock_drift_s", 0) or 0)) > MAX_CLOCK_DRIFT_S:
        issues.append(ISSUE_CLOCK_DRIFT)
    return issues


# --------------------------------------------------------------------------- FA-014
async def _existing_visit(session: AsyncSession, actor: User, body: VisitCheckIn) -> Visit | None:
    """A replayed check-in (same client id) returns the row that already exists."""
    ids = [i for i in (body.id, body.client_visit_id) if i is not None]
    if not ids:
        return None
    stmt = select(Visit).where(
        Visit.tenant_id == actor.tenant_id,
        (Visit.id.in_(ids)) | (Visit.client_visit_id.in_(ids)),
    )
    existing = (await session.execute(stmt)).scalars().first()
    if existing is None:
        return None
    if existing.officer_id != actor.id:
        raise ConflictError("This visit id belongs to another officer.")
    return existing


async def check_in(
    session: AsyncSession, actor: User, body: VisitCheckIn, *, now: datetime | None = None
) -> Visit:
    """FA-014 / VV-003: create the visit when the point is inside a geofence or at the
    meeting point; refuse it outside unless an override note came along."""
    now = now or _now()
    existing = await _existing_visit(session, actor, body)
    if existing is not None:
        return existing
    tenant_id = actor.tenant_id
    farmer = await _farmer(session, tenant_id, body.farmer_id)
    farm = None
    if body.farm_id is not None:
        farm = await geofence.farm_of(session, tenant_id, body.farm_id)
        if farm is None or farm.farmer_id != farmer.id:
            raise NotFoundError("Farm not found.")
    village = await geofence.village_of(session, tenant_id, body.village_id or farmer.village_id)
    settings = await settings_of(session, tenant_id)
    check = await geofence.evaluate(
        session,
        lat=body.checkin_point.lat,
        lon=body.checkin_point.lon,
        farm=farm,
        village=village,
        default_radius_m=settings.geofence_radius_m,
    )
    result = check.result
    if not check.allowed:
        if body.override_note is None:
            if check.target is None:
                detail = "No farm boundary or village meeting point to check against."
            else:
                where = "the farm boundary" if check.target == "farm" else "the meeting point"
                detail = (
                    f"{check.distance_m:.0f} m from {where}; the geofence is {check.radius_m} m. "
                    "Add an override note to request approval."
                )
            raise OutsideGeofenceError(
                detail,
                extra={
                    "distance_m": check.distance_m,
                    "target": check.target,
                    "radius_m": check.radius_m,
                },
            )
        result = GeofenceResult.OVERRIDE

    integrity = body.device_integrity.model_dump()
    issues = integrity_issues_of(integrity)
    initial = score_visit(
        geofence_result=result,
        confirmed=False,
        photos=[],
        checkin_at=body.checkin_at,
        checkout_at=None,
        checkin_lat=body.checkin_point.lat,
        checkin_lon=body.checkin_point.lon,
        min_duration_s=settings.min_visit_duration_s,
        integrity=DeviceIntegrity.from_dict(integrity),
        override_approved=False,
    )
    visit_id = body.id or uuid.uuid4()
    visit = Visit(
        id=visit_id,
        tenant_id=tenant_id,
        created_at=now,
        officer_id=actor.id,
        farmer_id=farmer.id,
        farm_id=farm.id if farm is not None else None,
        village_id=village.id if village is not None else None,
        purpose=body.purpose.value,
        checkin_at=body.checkin_at,
        checkin_point=point_wkt(body.checkin_point.lon, body.checkin_point.lat),
        checkin_accuracy_m=body.checkin_point.accuracy_m,
        geofence_result=result.value,
        override_note=body.override_note if result == GeofenceResult.OVERRIDE else None,
        status=VisitStatus.OPEN.value,
        confirmation_channel=ConfirmationChannel.NONE.value,
        score_components=dict(initial.components),  # live components while open; score at check-out
        device_integrity={**integrity, "issues": issues, "reported_at": now.isoformat()},
        flags=[],
        client_visit_id=body.client_visit_id or visit_id,
    )
    session.add(visit)
    await session.flush()
    await session.refresh(visit)  # load checkin_lat / checkin_lon and the server defaults

    if issues:
        log.warning(
            "integrity_signal",
            tenant_id=str(tenant_id),
            officer_id=str(actor.id),
            visit_id=str(visit.id),
            issues=issues,
            is_mock=bool(integrity["is_mock"]),
            is_rooted=bool(integrity["is_rooted"]),
            clock_drift_s=int(integrity["clock_drift_s"]),
        )
        await bus.dispatch(
            session,
            IntegrityEvent(
                tenant_id=tenant_id,
                officer_id=actor.id,
                visit_id=visit.id,
                issues=tuple(issues),
                is_mock=bool(integrity["is_mock"]),
                is_rooted=bool(integrity["is_rooted"]),
                clock_drift_s=int(integrity["clock_drift_s"]),
                at=now,
            ),
        )
    if result == GeofenceResult.OVERRIDE:
        request = OverrideRequest(
            tenant_id=tenant_id,
            created_at=now,
            visit_id=visit.id,
            note=body.override_note or "",
            requested_at=now,
            requested_by=actor.id,
            approver_role=OVERRIDE_APPROVER_ROLE,
        )
        session.add(request)
        await session.flush()
        log.info(
            "override_requested",
            tenant_id=str(tenant_id),
            visit_id=str(visit.id),
            officer_id=str(actor.id),
            distance_m=check.distance_m,
        )
        bus.publish(
            OverrideRequested(
                tenant_id=tenant_id,
                visit_id=visit.id,
                override_request_id=request.id,
                officer_id=actor.id,
                cluster_id=actor.cluster_id,
                approver_role=OVERRIDE_APPROVER_ROLE,
                note=request.note,
                distance_m=check.distance_m,
                at=now,
            )
        )
    log.info(
        "visit_checked_in",
        tenant_id=str(tenant_id),
        visit_id=str(visit.id),
        officer_id=str(actor.id),
        geofence_result=result.value,
        distance_m=check.distance_m,
    )
    # M4 event rules (VA-E01 integrity of the check-in, VA-E08 / VA-F08 photos synced early).
    await bus.dispatch(
        session,
        VisitCheckedIn(tenant_id=tenant_id, visit_id=visit.id, officer_id=actor.id, at=now),
    )
    return visit


async def decide_override(
    session: AsyncSession,
    actor: User,
    visit: Visit,
    *,
    approve: bool,
    note: str | None = None,
    now: datetime | None = None,
) -> OverrideRequest:
    """FA-014: the cluster head approves or rejects the pending override; rescored."""
    now = now or _now()
    request = await override_request_of(session, visit)
    if request is None or not request.pending:
        raise OverrideNotPendingError("This visit has no pending override request.")
    request.decision = (OverrideDecision.APPROVED if approve else OverrideDecision.REJECTED).value
    request.decided_at = now
    request.decided_by = actor.id
    request.decision_note = note
    visit.override_approved_by = actor.id if approve else None
    await session.flush()
    await rescore(session, visit)
    log.info(
        "override_decided",
        tenant_id=str(visit.tenant_id),
        visit_id=str(visit.id),
        decision=request.decision,
        decided_by=str(actor.id),
        role=actor.role,
    )
    return request


# --------------------------------------------------------------------------- FA-015
async def capture(session: AsyncSession, visit: Visit, body: VisitCapture) -> Visit:
    """Notes / crop stage / purpose: last writer wins (FA-025 merge_fields)."""
    changes = body.model_dump(exclude_unset=True)
    for key, value in changes.items():
        setattr(visit, key, value.value if hasattr(value, "value") else value)
    await session.flush()
    await session.refresh(visit)
    return visit


async def _duplicate(
    session: AsyncSession, visit: Visit, *, sha256: str, phash_hex: str | None
) -> bool:
    """VA-E08: the same bytes or the same perceptual hash already attached to another visit."""
    stmt = select(VisitPhoto.id).where(
        VisitPhoto.tenant_id == visit.tenant_id,
        VisitPhoto.visit_id != visit.id,
        VisitPhoto.deleted_at.is_(None),
    )
    if phash_hex is not None:
        stmt = stmt.where((VisitPhoto.sha256 == sha256) | (VisitPhoto.phash == phash_hex))
    else:
        stmt = stmt.where(VisitPhoto.sha256 == sha256)
    return (await session.execute(stmt.limit(1))).scalar_one_or_none() is not None


async def add_photo(
    session: AsyncSession,
    actor: User,
    visit: Visit,
    body: VisitPhotoCreate,
    *,
    blobs: BlobStore,
    now: datetime | None = None,
) -> VisitPhoto:
    """FA-015: attach an in-app photo; server time, sha256 and phash come from the blob."""
    now = now or _now()
    if body.id is not None:
        existing = await session.get(VisitPhoto, body.id)
        if existing is not None:
            if existing.visit_id != visit.id:
                raise ConflictError("This photo id belongs to another visit.")
            return existing
    if not body.taken_in_app:
        raise GalleryNotAllowedError("Visit photos must be taken with the in-app camera.")
    try:
        _bucket, key = parse_uri(body.blob_uri)
    except ValueError as exc:
        raise NotFoundError(f"Unknown blob {body.blob_uri}.") from exc
    if not key.startswith(f"{visit.tenant_id}/"):
        raise NotFoundError(f"Unknown blob {body.blob_uri}.")
    try:
        data = await blobs.get(body.blob_uri)
    except BlobNotFoundError as exc:
        raise NotFoundError("Blob not found; complete the upload first.") from exc
    digest = _sha(data)
    if body.sha256 is not None and body.sha256 != digest:
        raise PhotoShaMismatchError("sha256 does not match the uploaded blob.")
    phash_hex = phash(data)
    exif_time = body.exif_time
    exif_lat = body.exif_point.lat if body.exif_point is not None else None
    exif_lon = body.exif_point.lon if body.exif_point is not None else None
    if exif_time is None or exif_lat is None:
        exif = read_exif(data)
        exif_time = exif_time or exif.time
        if exif_lat is None and exif.lat is not None and exif.lon is not None:
            exif_lat, exif_lon = exif.lat, exif.lon

    flags: list[str] = []
    if exif_time is None:
        flags.append(PHOTO_FLAG_EXIF_TIME_MISSING)
    else:
        lower = visit.checkin_at - PHOTO_EXIF_TIME_TOLERANCE
        upper = (visit.checkout_at or max(now, visit.checkin_at)) + PHOTO_EXIF_TIME_TOLERANCE
        if not lower <= exif_time <= upper:
            flags.append(PHOTO_FLAG_EXIF_TIME_MISMATCH)
    if exif_lat is None or exif_lon is None:
        flags.append(PHOTO_FLAG_EXIF_GPS_MISSING)
    elif (
        haversine_m(visit.checkin_lat, visit.checkin_lon, exif_lat, exif_lon)
        > PHOTO_EXIF_DISTANCE_M
    ):
        flags.append(PHOTO_FLAG_EXIF_GPS_MISMATCH)
    if await _duplicate(session, visit, sha256=digest, phash_hex=phash_hex):
        flags.append(PHOTO_FLAG_DUPLICATE)

    photo = VisitPhoto(
        id=body.id or uuid.uuid4(),
        tenant_id=visit.tenant_id,
        created_at=now,
        visit_id=visit.id,
        blob_uri=body.blob_uri,
        sha256=digest,
        phash=phash_hex,
        exif_time=exif_time,
        exif_point=point_wkt(exif_lon, exif_lat)
        if exif_lat is not None and exif_lon is not None
        else None,
        taken_in_app=True,
        device_time=body.device_time,
        server_time=now,
        photo_flags=flags,
    )
    session.add(photo)
    await session.flush()
    await session.refresh(photo)
    await rescore(session, visit)
    if flags:
        log.info(
            "visit_photo_flagged",
            tenant_id=str(visit.tenant_id),
            visit_id=str(visit.id),
            photo_id=str(photo.id),
            flags=flags,
        )
    await bus.dispatch(  # M4: VA-E08 photo integrity, VA-F08 reuse across farmers
        session,
        VisitPhotoAdded(
            tenant_id=visit.tenant_id,
            visit_id=visit.id,
            photo_id=photo.id,
            photo_flags=tuple(flags),
            at=now,
        ),
    )
    return photo


# --------------------------------------------------------------------------- FA-016
def issue_confirm_token(
    settings: Settings,
    *,
    tenant_id: uuid.UUID,
    visit_id: uuid.UUID,
    confirmation_id: uuid.UUID,
    channel: str,
    now: datetime,
) -> tuple[str, datetime]:
    """Signed token the farmer app presents (push payload or QR); bound to the request row."""
    expires_at = now + timedelta(seconds=settings.visit_confirm_token_ttl_seconds)
    claims = {
        "iss": settings.jwt_issuer,
        "typ": CONFIRM_JWT_TYP,
        "tid": str(tenant_id),
        "vid": str(visit_id),
        "cid": str(confirmation_id),
        "ch": channel,
        "iat": int(now.timestamp()),
        "exp": int(expires_at.timestamp()),
        "jti": uuid.uuid4().hex,
    }
    return jwt.encode(
        claims, settings.jwt_signing_key, algorithm=settings.jwt_algorithm
    ), expires_at


def decode_confirm_token(
    settings: Settings, token: str, *, tenant_id: uuid.UUID, visit_id: uuid.UUID, now: datetime
) -> dict[str, Any]:
    try:
        claims: dict[str, Any] = jwt.decode(
            token,
            settings.jwt_signing_key,
            algorithms=[settings.jwt_algorithm],
            issuer=settings.jwt_issuer,
            options={"verify_exp": False, "verify_iat": False, "require": ["exp", "cid", "vid"]},
        )
    except jwt.PyJWTError as exc:
        raise ConfirmationTokenInvalidError("Invalid confirmation token.") from exc
    if claims.get("typ") != CONFIRM_JWT_TYP:
        raise ConfirmationTokenInvalidError("Invalid confirmation token.")
    if claims.get("tid") != str(tenant_id) or claims.get("vid") != str(visit_id):
        raise ConfirmationTokenInvalidError("Token does not belong to this visit.")
    if int(claims["exp"]) <= int(now.timestamp()):
        raise ConfirmationTokenInvalidError("Confirmation token expired; ask for a new one.")
    return claims


async def _expire_pending(
    session: AsyncSession, visit: Visit, *, channel: str | None = None
) -> None:
    for row in await confirmations_of(session, visit):
        if row.status == ConfirmationStatus.PENDING and (channel is None or row.channel == channel):
            row.status = ConfirmationStatus.EXPIRED.value


async def request_confirmation(
    session: AsyncSession,
    actor: User,
    visit: Visit,
    channel: str,
    *,
    services: AuthServices,
) -> ConfirmationStart:
    """FA-016: start one channel; a new request on the same channel supersedes the old one."""
    if visit.confirmed_at is not None:
        raise VisitAlreadyConfirmedError("This visit is already confirmed.")
    now = services.clock.now()
    settings = services.settings
    farmer = await _farmer(session, visit.tenant_id, visit.farmer_id)
    await _expire_pending(session, visit, channel=channel)
    row = VisitConfirmation(
        id=uuid.uuid4(),
        tenant_id=visit.tenant_id,
        created_at=now,
        visit_id=visit.id,
        channel=channel,
        status=ConfirmationStatus.PENDING.value,
        farmer_phone_last4=farmer.phone[-4:],
        requested_at=now,
    )
    if channel == ConfirmationChannel.SMS_OTP:
        sent = await services.otp.send(
            session,
            phone=farmer.phone,
            purpose=OTP_PURPOSE,
            tenant_id=visit.tenant_id,
            device_id=_device_of(actor),
        )
        row.otp_challenge_id = sent.challenge.id
        row.expires_at = sent.challenge.expires_at
        session.add(row)
        await session.flush()
        return ConfirmationStart(
            row=row,
            phone_masked=mask_phone(farmer.phone),
            expires_in=settings.otp_ttl_seconds,
            resend_after=settings.otp_resend_after_seconds,
            resends_left=sent.resends_left,
        )
    if channel == ConfirmationChannel.APP_PUSH and farmer.user_id is None:
        raise ConfirmationChannelInvalidError(
            "This farmer has no app account; use an SMS code or a QR instead."
        )
    token, expires_at = issue_confirm_token(
        settings,
        tenant_id=visit.tenant_id,
        visit_id=visit.id,
        confirmation_id=row.id,
        channel=channel,
        now=now,
    )
    row.token_hash = _sha(token)
    row.expires_at = expires_at
    session.add(row)
    await session.flush()
    if channel == ConfirmationChannel.APP_PUSH:
        if farmer.user_id is None:  # checked above; keeps the type narrow
            raise ConfirmationChannelInvalidError("This farmer has no app account.")
        bus.publish(
            ConfirmationRequested(
                tenant_id=visit.tenant_id,
                visit_id=visit.id,
                confirmation_id=row.id,
                farmer_id=farmer.id,
                farmer_user_id=farmer.user_id,
                officer_id=actor.id,
                channel=channel,
                token=token,
                expires_at=expires_at,
            )
        )
        return ConfirmationStart(row=row, expires_in=settings.visit_confirm_token_ttl_seconds)
    return ConfirmationStart(
        row=row, expires_in=settings.visit_confirm_token_ttl_seconds, token=token
    )


async def _mark_confirmed(
    session: AsyncSession,
    visit: Visit,
    row: VisitConfirmation,
    *,
    now: datetime,
    device_id: str | None,
) -> None:
    row.status = ConfirmationStatus.CONFIRMED.value
    row.confirmed_at = now
    row.confirmed_via_device_id = device_id
    visit.confirmation_channel = row.channel
    visit.confirmed_at = now
    await session.flush()
    await _expire_pending(session, visit)
    await rescore(session, visit)
    log.info(
        "visit_confirmed",
        tenant_id=str(visit.tenant_id),
        visit_id=str(visit.id),
        channel=row.channel,
    )
    await bus.dispatch(
        session,
        VisitConfirmed(
            tenant_id=visit.tenant_id,
            visit_id=visit.id,
            confirmation_id=row.id,
            channel=row.channel,
            at=now,
        ),
    )


async def confirm_with_otp(
    session: AsyncSession,
    actor: User,
    visit: Visit,
    code: str,
    *,
    services: AuthServices,
) -> VisitConfirmation:
    """FA-016 ``sms_otp`` on the officer's phone: verify the code the farmer read out."""
    if visit.confirmed_at is not None:
        raise VisitAlreadyConfirmedError("This visit is already confirmed.")
    pending = next(
        (
            c
            for c in reversed(await confirmations_of(session, visit))
            if c.channel == ConfirmationChannel.SMS_OTP and c.status == ConfirmationStatus.PENDING
        ),
        None,
    )
    if pending is None:
        raise ConfirmationNotRequestedError("Request an SMS code for this visit first.")
    farmer = await _farmer(session, visit.tenant_id, visit.farmer_id)
    challenge = await services.otp.verify(
        session, phone=farmer.phone, code=code, purpose=OTP_PURPOSE, tenant_id=visit.tenant_id
    )
    if pending.otp_challenge_id != challenge.id:
        pending.otp_challenge_id = challenge.id  # a later resend for the same farmer
    await _mark_confirmed(
        session, visit, pending, now=services.clock.now(), device_id=_device_of(actor)
    )
    return pending


async def farmer_confirm(
    session: AsyncSession,
    actor: User,
    visit: Visit,
    body: FarmerConfirm,
    *,
    settings: Settings,
    now: datetime | None = None,
) -> VisitConfirmation:
    """FA-016 ``app_push`` / ``qr`` on the farmer's phone (FM-011 rating rides along)."""
    now = now or _now()
    claims = decode_confirm_token(
        settings, body.token, tenant_id=visit.tenant_id, visit_id=visit.id, now=now
    )
    try:
        row = await session.get(VisitConfirmation, uuid.UUID(str(claims["cid"])))
    except ValueError:
        row = None
    if row is None or row.visit_id != visit.id or row.token_hash != _sha(body.token):
        raise ConfirmationTokenInvalidError("Unknown confirmation token.")
    if row.status == ConfirmationStatus.CONFIRMED:
        if body.rating is not None:  # a replay may still add the rating
            row.rating, row.rating_reason = body.rating, body.reason
            await session.flush()
        return row
    if visit.confirmed_at is not None:
        raise VisitAlreadyConfirmedError("This visit was confirmed through another channel.")
    if row.status != ConfirmationStatus.PENDING or (
        row.expires_at is not None and row.expires_at <= now
    ):
        raise ConfirmationTokenInvalidError("Confirmation token expired; ask for a new one.")
    row.rating, row.rating_reason = body.rating, body.reason
    await _mark_confirmed(session, visit, row, now=now, device_id=_device_of(actor))
    return row


