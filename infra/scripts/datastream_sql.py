#!/usr/bin/env python3
"""Print the one-time (idempotent) Postgres SQL Datastream needs, from the column allowlist.

Migrations own the database schema, and Terraform never holds a database password, so the
replication plumbing is applied by a human (docs/runbooks/datastream-cdc-setup.md):

  * role `datastream`: LOGIN REPLICATION, no superuser, no DML;
  * column-level SELECT on exactly the allowlisted columns (AN-014: the login cannot even read
    a name or a phone), USAGE on schema public;
  * an RLS read policy per replicated table (every table has FORCE ROW LEVEL SECURITY keyed on
    app.tenant_id, ADR 0003; the backfill must see every tenant);
  * publication `farmerapp_datastream` over the allowlisted tables with the same column lists
    (Postgres 15+), created or re-synced with ALTER PUBLICATION ... SET TABLE;
  * logical replication slot `farmerapp_datastream` (pgoutput), only if missing.

Two parts, because Cloud SQL splits the privileges:
  --part admin   role + slot, run as the built-in `postgres` user (cloudsqlsuperuser: may create
                 REPLICATION roles and slots)
  --part owner   grants, RLS policies, publication, run as the tables' owner (a member of
                 farmerapp_migrate): only the owner may add policies and publish a table

Usage:  python3 infra/scripts/datastream_sql.py --part admin   (stdlib only)
        python3 infra/scripts/datastream_sql.py --part owner
Re-run `--part owner` after adding a table or column to replicated_columns.json.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ALLOWLIST = Path(__file__).resolve().parents[1] / "modules" / "analytics" / "replicated_columns.json"
ROLE = "datastream"
PUBLICATION = "farmerapp_datastream"
SLOT = "farmerapp_datastream"


def q(ident: str) -> str:
    return '"' + ident.replace('"', '""') + '"'


def admin() -> list[str]:
    return [
        "-- GENERATED by infra/scripts/datastream_sql.py --part admin. Idempotent.",
        "-- Run as the built-in `postgres` user on the target Cloud SQL instance.",
        "",
        "-- 1. The login (its password is set separately with \\password, never in this file).",
        "DO $$",
        "BEGIN",
        f"    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{ROLE}') THEN",
        f"        CREATE ROLE {q(ROLE)} LOGIN REPLICATION NOSUPERUSER NOCREATEDB NOCREATEROLE;",
        "    ELSE",
        f"        ALTER ROLE {q(ROLE)} LOGIN REPLICATION NOSUPERUSER NOCREATEDB NOCREATEROLE;",
        "    END IF;",
        "END $$;",
        "",
        "-- 2. Replication slot (skipped when it exists).",
        f"SELECT pg_create_logical_replication_slot('{SLOT}', 'pgoutput')",
        f"WHERE NOT EXISTS (SELECT 1 FROM pg_replication_slots WHERE slot_name = '{SLOT}');",
    ]


def owner() -> list[str]:
    allow = {t: c for t, c in json.loads(ALLOWLIST.read_text()).items() if not t.startswith("_")}
    out: list[str] = [
        "-- GENERATED by infra/scripts/datastream_sql.py --part owner from replicated_columns.json.",
        "-- Idempotent. Run as a member of farmerapp_migrate (the tables' owner).",
        "BEGIN;",
        f"GRANT USAGE ON SCHEMA public TO {q(ROLE)};",
        "",
        "-- 1. Column-level SELECT on the allowlist only (AN-014), and an RLS read policy.",
    ]
    for table, cols in allow.items():
        t = f"public.{q(table)}"
        collist = ", ".join(q(c) for c in cols)
        out += [
            f"REVOKE ALL ON {t} FROM {q(ROLE)};",
            f"GRANT SELECT ({collist}) ON {t} TO {q(ROLE)};",
            f"DROP POLICY IF EXISTS datastream_read ON {t};",
            f"CREATE POLICY datastream_read ON {t} FOR SELECT TO {q(ROLE)} USING (true);",
        ]
    tables = ",\n    ".join(f"public.{q(t)} ({', '.join(q(c) for c in cols)})" for t, cols in allow.items())
    out += [
        "",
        "-- 2. Publication over the same tables and columns.",
        "DO $$",
        "BEGIN",
        f"    IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = '{PUBLICATION}') THEN",
        f"        CREATE PUBLICATION {q(PUBLICATION)};",
        "    END IF;",
        "END $$;",
        f"ALTER PUBLICATION {q(PUBLICATION)} SET TABLE\n    {tables};",
        "",
        "COMMIT;",
    ]
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--part", choices=["admin", "owner"], required=True)
    args = parser.parse_args()
    print("\n".join(admin() if args.part == "admin" else owner()))


if __name__ == "__main__":
    main()
